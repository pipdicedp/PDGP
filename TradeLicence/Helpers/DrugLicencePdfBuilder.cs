using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using TradeLicence.Models.Drugs;

namespace TradeLicence.Helpers
{
    /// <summary>
    /// SAMPLE approval document an applicant downloads once the GM approves a Form 20A / 21A application.
    /// It is a placeholder (watermarked "SAMPLE") - replace the body of <see cref="Build"/> with the
    /// official licence wording when it is available. Static on purpose, like CafApprovalPdfBuilder.
    /// QuestPDF's licence is set once in Program.cs.
    /// </summary>
    public static class DrugLicencePdfBuilder
    {
        public static byte[] Build(DrugFormDefinition form, DrugLicenceApplicationBase app,
                                   IReadOnlyList<DrugLicencePharmacist> pharmacists, DateTime approvedOnUtc)
        {
            var dateText = ToIndiaTime(approvedOnUtc).ToString("dd-MM-yyyy");
            var address = string.Join(", ", new[] { app.AddressOfTheFirm, app.Landmark, app.Districts, app.PostalZipCode }
                .Where(x => !string.IsNullOrWhiteSpace(x)).Select(x => x!.Trim().TrimEnd(',')));

            return Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(2.2f, Unit.Centimetre);
                    page.DefaultTextStyle(x => x.FontSize(11).LineHeight(1.4f));

                    // diagonal watermark so nobody mistakes this for a real licence
                    page.Foreground().AlignMiddle().AlignCenter().Rotate(-35)
                        .Text("SAMPLE").FontSize(110).Bold().FontColor(Colors.Grey.Lighten3);

                    page.Content().Column(col =>
                    {
                        col.Spacing(10);

                        col.Item().AlignCenter().Text("GOVERNMENT OF PUDUCHERRY").Bold().FontSize(14);
                        col.Item().AlignCenter().Text("DEPARTMENT OF INDUSTRIES AND COMMERCE").Bold().FontSize(12);
                        col.Item().AlignCenter().Text($"RESTRICTED DRUG LICENCE - FORM {form.Code}").Bold().FontSize(12);
                        col.Item().AlignCenter().Text("(SAMPLE DOCUMENT - NOT A VALID LICENCE)").FontSize(10).FontColor(Colors.Red.Darken2);

                        col.Item().PaddingTop(8).Row(r =>
                        {
                            r.RelativeItem().Text($"Application No.: {OrDash(app.ApplicationNumber)}");
                            r.RelativeItem().AlignRight().Text($"Puducherry, dt. {dateText}");
                        });

                        col.Item().PaddingTop(6).Text(t =>
                        {
                            t.Justify();
                            t.Span("This is to certify that the application of ");
                            t.Span(OrDash(app.FirmName)).Bold();
                            t.Span($" for {(app.IsRenewal ? "renewal" : "grant")} of a Restricted Drug Licence in Form {form.Code} has been examined and approved by the competent authority, subject to the provisions of the Drugs and Cosmetics Act, 1940 and the Rules made thereunder.");
                        });

                        col.Item().PaddingTop(4).Column(d =>
                        {
                            d.Spacing(3);
                            Line(d, "Applicant", app.ApplicantName);
                            Line(d, "Firm", app.FirmName);
                            Line(d, "Manager / Incharge", app.ManagerInchargeName);
                            Line(d, "Constitution", app.ConstitutionType);
                            Line(d, "Address of the firm", address);
                            Line(d, "Schedule of drugs", app.ScheduleOfDrugsLabel);
                            Line(d, "Cold storage", app.ColdStorage ? "Yes" : "No");
                            Line(d, "Open 24 hours", app.TwentyFourHours ? "Yes" : "No");
                        });

                        if (pharmacists.Count > 0)
                        {
                            col.Item().PaddingTop(4).Text("Pharmacist / Competent person(s)").Bold();
                            foreach (var p in pharmacists)
                            {
                                col.Item().Text($"-  {p.Name}  |  {OrDash(p.Qualification)}  |  Council No. {OrDash(p.CouncilNo)}");
                            }
                        }

                        col.Item().PaddingTop(50).AlignRight().Column(s =>
                        {
                            s.Item().AlignRight().Text("SIGNATURE OF SIGNING AUTHORITY").Bold();
                            s.Item().AlignRight().Text("PUDUCHERRY").Bold();
                        });

                        col.Item().PaddingTop(20).Text("Note: this sample is generated by the portal until the official licence certificate format is configured.")
                            .FontSize(9).Italic().FontColor(Colors.Grey.Darken1);
                    });
                });
            }).GeneratePdf();
        }

        private static void Line(ColumnDescriptor col, string label, string? value)
        {
            col.Item().Row(r =>
            {
                r.ConstantItem(150).Text(label).SemiBold();
                r.RelativeItem().Text(OrDash(value));
            });
        }

        private static string OrDash(string? value) => string.IsNullOrWhiteSpace(value) ? "\u2014" : value.Trim();

        private static DateTime ToIndiaTime(DateTime utc)
        {
            var asUtc = DateTime.SpecifyKind(utc, DateTimeKind.Utc);
            foreach (var id in new[] { "India Standard Time", "Asia/Kolkata" })
            {
                try { return TimeZoneInfo.ConvertTimeFromUtc(asUtc, TimeZoneInfo.FindSystemTimeZoneById(id)); }
                catch (TimeZoneNotFoundException) { }
                catch (InvalidTimeZoneException) { }
            }
            return asUtc.AddHours(5.5);
        }
    }
}
